"""Turn a saved failing trial into a runnable regression test (HTTP only): red on the buggy app, green on a fixed one.
usage (repo root, target app running): python -m controller.make_test SCENARIO [failing_trial.json]
Without a file it attacks the running app to find a failing trial. Output: tests/generated/test_<scenario>_race.py"""
import json, sys, pathlib
from . import config, attacker

TEMPLATE = '''"""Regression test generated by GlitchHunter from a failing run ({source}).
Replays the failing schedule: {n} simultaneous {method} {path} with {params}, starting from {initial}, repeated {trials} times
with a {delay} ms test pause. It fails if more was taken out than existed, or if the final state does not add up.
Needs the target app running: set GH_TARGET_URL (default {base}). Run with pytest, or: python {fname}"""
import os
import sys
import threading

import httpx

BASE = os.environ.get("GH_TARGET_URL", "{base}")
METHOD, PATH, PARAMS = {method!r}, {path!r}, {params!r}
RESET_PATH, RESET_PARAMS, STATE_PATH = {reset_path!r}, {reset_params!r}, {state_path!r}
N, DELAY, TRIALS = {n}, {delay}, {trials}
KEY, INITIAL, UNIT = {key!r}, {initial_value}, {unit}


def one_trial(cl):
    cl.post(RESET_PATH, params=RESET_PARAMS)
    barrier, statuses = threading.Barrier(N), [None] * N

    def go(i):
        barrier.wait()
        statuses[i] = cl.request(METHOD, PATH, params=PARAMS, headers={{"X-Race-Delay": str(DELAY)}}).status_code

    threads = [threading.Thread(target=go, args=(i,)) for i in range(N)]
    [t.start() for t in threads]
    [t.join() for t in threads]
    return statuses, cl.get(STATE_PATH).json()[KEY]


def test_no_overdraw_under_concurrency():
    with httpx.Client(base_url=BASE, timeout=30) as cl:
        for trial in range(TRIALS):
            statuses, final = one_trial(cl)
            taken = sum(1 for s in statuses if s == 200) * UNIT
            assert taken <= INITIAL, f"trial {{trial}}: {{taken}} was taken out of {{INITIAL}} (statuses {{statuses}})"
            assert final == INITIAL - taken, f"trial {{trial}}: {{KEY}} ended at {{final}}, expected {{INITIAL - taken}} (statuses {{statuses}})"


if __name__ == "__main__":
    try:
        test_no_overdraw_under_concurrency()
        print("PASS: no violation in {trials} simultaneous trials")
    except AssertionError as e:
        print("FAIL:", e)
        sys.exit(1)
'''

def generate(sc, trial, source):
    r0 = trial["requests"][0]; key = sc["initial_columns"][0]
    reset_params = {**sc["reset"]["params"]}
    reset_params.update({k: v for k, v in trial["initial_state"].items() if v is not None})
    code = TEMPLATE.format(source=source, n=trial["n"], method=r0["method"], path=r0["path"], params=r0["params"], initial=trial["initial_state"],
                           trials=20, delay=trial["delay_ms"] or 30, base=sc["base_url"], fname=f"test_{sc['name']}_race.py",
                           reset_path=sc["reset"]["path"], reset_params=reset_params, state_path=sc["state_path"],
                           key=key, initial_value=trial["initial_state"][key], unit=next(iter(r0["params"].values())))
    out = config.ROOT / "tests" / "generated"; out.mkdir(parents=True, exist_ok=True)
    p = out / f"test_{sc['name']}_race.py"; p.write_text(code, encoding="utf-8"); return p

if __name__ == "__main__":
    cfg = config.load(); sc = config.scenario(cfg, sys.argv[1])
    if len(sys.argv) > 2:
        trial = json.loads(pathlib.Path(sys.argv[2]).read_text(encoding="utf-8")); source = pathlib.Path(sys.argv[2]).name
    else:
        inv = {r["id"]: r["sql"] for r in attacker.builtin(sc)}
        _, failing = attacker.attack(cfg, sc, inv, 20, delay=30, run_id=f"maketest_{sc['name']}", save=False)
        if not failing: sys.exit("no failing trial found: is the app running in MODE=vuln?")
        trial = failing[0]; source = f"a live attack on {sc['base_url']}"
    print("wrote", generate(sc, trial, source))
